-- 0002_code_pow.sql
-- 验证码表增加「发码时已通过人机验证」标记。
--
-- 背景：人机验证的挑战是一次性的（pow_challenges.consumed_at）。
-- 原实现里 sendCode 和 signup 各自 consumePow 一次，但前端只能在
-- 「获取验证码」时解一次挑战（用户要求：注册的验证在点发码时做），
-- 于是注册提交必然因为挑战已被消费而返回 captcha_required。
--
-- 现在把验证结果落在验证码记录上：发码时 consumePow 成功才写入
-- pow_verified=1，注册/找回密码时校验「这次验证码的发送通过过人机验证」。
-- 一次验证绑定一次发码，仍然能挡住「刷接口滥发邮件」。
-- ============================================================
ALTER TABLE email_codes ADD COLUMN pow_verified INTEGER NOT NULL DEFAULT 0;
